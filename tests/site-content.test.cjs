const { readFileSync } = require('node:fs')
const { test } = require('node:test')
const assert = require('node:assert/strict')

const read = (file) => readFileSync(new URL(`../${file}`, `file://${__filename}`), 'utf8')

test('home page has the updated event and contact details', async () => {
  assert.match(read('src/components/Hero.vue'), /Visit our booth at the park during the Summer's End Festival Aug 22/)
  assert.match(read('src/components/Hero.vue'), /Interested in volunteering\?/)
  const { festivalIsOver } = await import('../src/festival.mjs')
  assert.equal(festivalIsOver(new Date(2026, 7, 22, 23, 59)), false)
  assert.equal(festivalIsOver(new Date(2026, 7, 23)), true)
  const contact = read('src/components/Contact.vue')
  assert.match(contact, /50 E North Street, Rossville, IN 46065/)
  assert.match(contact, /rvassec@gmail\.com/)
  assert.doesNotMatch(contact, /379-2999|rvas@geetel\.net/)
  assert.match(contact, /Emergency Resources/)
  assert.match(contact, /tel:911/)
  assert.match(contact, /tel:18002221222/)
  assert.match(contact, /tel:988/)
  assert.match(contact, /tel:211/)
  assert.match(contact, /Email is not monitored for emergencies/)
  const history = read('src/components/History.vue')
  assert.match(history, /mailto:rvassec@gmail\.com/)
  assert.doesNotMatch(history, /765-379-2998|business number/)
})

test('navigation and donation page offer each requested giving option', () => {
  assert.match(read('src/components/NavBar.vue'), /href="\/donate\.html"/)
  assert.match(read('donate.html'), /src="\/src\/donate\.js"/)
  assert.match(read('vite.config.mjs'), /input: \['index\.html', 'donate\.html'\]/)
  const donate = read('src/components/Donate.vue')
  assert.match(donate, /Donations go toward equipment, training, and general upkeep of the squad headquarters/)
  assert.doesNotMatch(donate, /secure donation on Stripe/)
  assert.match(donate, /text-center text-2xl font-bold text-blue-900">Make a one-time gift/)
  assert.match(donate, /text-center text-2xl font-bold text-blue-900">Give Monthly/)
  assert.match(donate, /https:\/\/donate\.stripe\.com\/8x2fZi0ws8QQ6CM1wX67S01/)
  assert.match(donate, /\/donation-qr\.png/)
  assert.match(donate, /https:\/\/donate\.stripe\.com\/dRmcN6frm1oobX62B167S03/)
  assert.match(donate, /\/monthly-donation-qr\.png/)
  assert.match(donate, /Choose your monthly amount/)
  assert.doesNotMatch(donate, /monthlyGifts|Monthly Stripe links coming soon/)
  assert.match(read('src/donate.js'), /render: \(\) => h/)
})

test('funding FAQ reflects current county and V.A.S. responsibilities', () => {
  const faq = read('src/components/Faq.vue')
  assert.match(faq, /The county provides the ambulance, fuel, truck maintenance, and some training/)
  assert.match(faq, /V\.A\.S\. remains responsible for the cost of EMT and EMR classes, some training, building & grounds maintenance & repair, and some supplies/)
  assert.match(faq, /All EMTs, EMRs, and drivers are volunteers/)
  assert.doesNotMatch(faq, /stipend|ambulace|purchases ambulances/)
})

test('Netlify uses a Node version supported by Vite', () => {
  assert.equal(read('.nvmrc').trim(), '22.12.0')
})
